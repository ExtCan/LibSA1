/* the generated table uses the header's numbers */
typedef char sa1em_class_check[(SA1_EMOTE_CLASS_SUPER == 14u && SA1_EMOTE_F_EXTRA == 0x20u &&
                                 SA1_EMOTE_F_OTHER_OBJECT == 0x10u && SA1_EMOTE_ROW == 0u && SA1_EMOTE_EXTRA == 1u)
                                    ? 1
                                    : -1];
/* round 100-EV: the cutscene animations' numbers (sadc docs/research/gsa1_100_master.md 5.2) */
typedef char sa1em_event_check[(SA1_EMOTE_EVENT == 2u && SA1_EMOTE_CLASS_EVENT == 15u && SA1_EMOTE_F_EVENT == 0x100u &&
                                 SA1_EMOTE_F_ROOT_MOVES == 0x200u && SA1_EMOTE_F_LIFTED == 0x400u &&
                                 SA1_EMOTE_F_RESTS_ON == 0x800u && SA1EM_F_LOOP < SA1_EMOTE_F_EVENT)
                                    ? 1
                                    : -1];

/* round 0.9.9 (gsa1_099_plan.md 3.2, the gate per feature; the method of SA1FO_BUILT): emotes on a follower id. The optimised archives answer today's refusal until this is 1 (set right
   before 099-lib-follow's final gate); the lane's own tests run the -O0 build */
#define SA1EM_FOL_BUILT 1
#if defined(__OPTIMIZE__) && !SA1EM_FOL_BUILT
#define SA1EM_FOL_GATED 1
#else
#define SA1EM_FOL_GATED 0
#endif

#define SA1EM_KNOWN_FLAGS (SA1_EMOTE_CHAIN | SA1_EMOTE_NO_TRAIL | SA1_EMOTE_IN_AIR | SA1_EMOTE_KEEP_INPUT | SA1_EMOTE_NO_PROPS | \
                           SA1_EMOTE_HOLD)

const sa1em_entry *sa1em_find(const sa1em_list *l, uint32_t source, uint32_t index, uint32_t *pos)
{
    uint32_t i;
    if (l == NULL) {
        return NULL;
    }
    for (i = 0; i < l->count; i++) {
        if (l->e[i].source == source && l->e[i].index == index) {
            if (pos != NULL) {
                *pos = i;
            }
            return &l->e[i];
        }
    }
    return NULL;
}

static int sa1em_loop_mode(int32_t mode)
{
    return mode == 3 || mode == 9 || mode == 10 || mode == 11 || mode == 12;
}

/* the catalogue needs the disc and the kind's character set (the rows' frames and play modes) */
static int sa1em_loaded(const sa1_context *ctx, int32_t kind)
{
    return ctx != NULL && ctx->disc_loaded && kind >= 0 && kind < SA1_CHAR_COUNT && ctx->chars[kind].loaded;
}

/* round 100-EV: the cutscene animations of a (kind, form): after the rows and extras of the normal form only (kind 8 and
   the General form have none: emotes_ev.md 2.3) */
static const sa1ev_list *sa1em_events_of(int32_t kind, uint32_t form)
{
    return (form == SA1_EMOTE_FORM_NORMAL && kind != SA1_CHAR_SUPER_SONIC) ? sa1ev_list_of(kind) : NULL;
}

uint32_t sa1_emote_count(const sa1_context *ctx, int32_t kind, uint32_t form)
{
    const sa1em_list *l;
    const sa1ev_list *v;
    if (!sa1em_loaded(ctx, kind)) {
        return 0;
    }
    l = sa1em_list_of(kind, form);
    v = l != NULL ? sa1em_events_of(kind, form) : NULL;
    return (l != NULL ? l->count : 0u) + (v != NULL ? v->count : 0u);
}

/* round 100-EV: an EVENT entry's catalogue fields (sadc docs/research/emotes_ev.md 3.2, 7.1) */
static void sa1em_event_info(int32_t kind, uint32_t index, const sa1ev_entry *ev, sa1_emote_info *info)
{
    const sa1ev_file *f = ev->file < sa1ev_num_files ? &sa1ev_files[ev->file] : NULL;
    (void)kind;
    info->source = SA1_EMOTE_EVENT;
    info->index = index;
    info->internal_name = ev->name;
    info->label = "";                   /* review RX.10: no SA Tools label ships */
    info->emote_class = SA1_EMOTE_CLASS_EVENT;
    info->flags = ev->flags;
    info->frames = ev->frames;
    info->play = ev->loop ? SA1_EMOTE_PLAY_LOOP : SA1_EMOTE_PLAY_ONCE;
    info->dup_of = -1;
    info->event = ev->event;
    info->event_order = ev->order;
    info->cast = f != NULL ? f->cast : 0u;
    info->pace = ev->pace;
    info->lift = ev->lift;
    info->num_events = ev->num_events;
    info->events = ev->events;
}

sa1_status sa1_emote_get(const sa1_context *ctx, int32_t kind, uint32_t form, uint32_t i, sa1_emote_info *out)
{
    sa1_emote_info info;
    const sa1em_list *l;
    const sa1em_entry *e;
    if (ctx == NULL || out == NULL || out->struct_size < sizeof(uint32_t)) {
        return SA1_ERR_INVALID_ARGUMENT;
    }
    if (!sa1em_loaded(ctx, kind)) {
        return SA1_ERR_NOT_LOADED;
    }
    l = sa1em_list_of(kind, form);
    if (l == NULL) {
        return SA1_ERR_NOT_FOUND;
    }
    memset(&info, 0, sizeof info);
    info.struct_size = sizeof info;
    if (i >= l->count) {
        /* round 100-EV: the cutscene animations after the rows and extras */
        const sa1ev_list *v = sa1em_events_of(kind, form);
        if (v == NULL || i - l->count >= v->count) {
            return SA1_ERR_NOT_FOUND;
        }
        sa1em_event_info(kind, i - l->count, &v->e[i - l->count], &info);
        sa1_copy_out(out, &info, sizeof info);
        return SA1_OK;
    }
    e = &l->e[i];
    info.source = e->source;
    info.index = e->index;
    info.internal_name = e->name;
    info.label = e->label;
    info.emote_class = e->cls;
    info.flags = e->flags;
    info.dup_of = e->dup_of;
    if (e->source == SA1_EMOTE_EXTRA) {
        info.frames = e->frames;
        info.play = (e->flags & SA1EM_F_LOOP) ? SA1_EMOTE_PLAY_LOOP : SA1_EMOTE_PLAY_ONCE;
    } else {
        sa1_action_info ai;
        memset(&ai, 0, sizeof ai);
        ai.struct_size = sizeof ai;
        if (sa1_action_info_get(ctx, kind, e->index, &ai) == SA1_OK) {
            info.frames = ai.status == SA1_ACTION_OK ? ai.num_frames : 0u;
            info.play = sa1em_loop_mode(ai.mode) ? SA1_EMOTE_PLAY_LOOP : SA1_EMOTE_PLAY_ONCE;
        } else {
            info.play = SA1_EMOTE_PLAY_ONCE;
        }
    }
    sa1_copy_out(out, &info, sizeof info);
    return SA1_OK;
}

/* the character's kind (-1: no such character) */
static int32_t sa1em_kind_of(const sa1_context *ctx, sa1_character_id id)
{
    uint32_t slot = ((uint32_t)id & 0xFFFFu) - 1u, gen = ((uint32_t)id >> 16) & 0x7FFFu;
    if (ctx == NULL || id <= 0 || slot >= SA1_MAX_INSTANCES || ctx->inst[slot] == NULL || ctx->inst_gen[slot] != gen) {
        return -1;
    }
    return ctx->inst[slot]->kind;
}

static const char *sa1em_who(int32_t kind, uint32_t form)
{
    static const char *const names[SA1_CHAR_COUNT] = { "Sonic", "Eggman", "Tails", "Knuckles", "Tikal", "Amy", "E-102",
                                                       "Big", "Super Sonic" };
    if (kind == SA1_CHAR_SONIC && form == SA1_EMOTE_FORM_SUPER) {
        return "Super Sonic";
    }
    return kind >= 0 && kind < SA1_CHAR_COUNT ? names[kind] : "this character";
}

/* the name of an entry for a refusal: the (kind, form) list, else the kind's other list, else "row N" / "extra N" */
static void sa1em_name(int32_t kind, uint32_t form, const sa1_emote_item *it, char *buf, size_t n)
{
    const sa1em_entry *e;
    if (it->source == SA1_EMOTE_EVENT) {
        /* round 100-EV: the cutscene animations have the same names in every form ("ev0003_2") */
        const sa1ev_entry *v = sa1ev_entry_of(kind == SA1_CHAR_SUPER_SONIC ? SA1_CHAR_SONIC : kind, it->index);
        if (v != NULL) {
            snprintf(buf, n, "%s", v->name);
        } else {
            snprintf(buf, n, "cutscene animation %u", (unsigned)it->index);
        }
        return;
    }
    e = sa1em_find(sa1em_list_of(kind, form), it->source, it->index, NULL);
    if (e == NULL && kind == SA1_CHAR_SONIC) {
        e = sa1em_find(sa1em_list_of(kind, form == SA1_EMOTE_FORM_SUPER ? SA1_EMOTE_FORM_NORMAL : SA1_EMOTE_FORM_SUPER),
                       it->source, it->index, NULL);
    }
    if (e != NULL) {
        snprintf(buf, n, "%s", e->name);
    } else {
        snprintf(buf, n, "%s %u", it->source == SA1_EMOTE_EXTRA ? "extra" : "row", (unsigned)it->index);
    }
}

/* the argument syntax (nothing about the character) */
static sa1_status sa1em_syntax(sa1_context *ctx, const sa1_emote *e)
{
    uint32_t i;
    if (e == NULL || e->struct_size < sizeof(sa1_emote)) {
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: emote NULL or struct_size %u < %u",
                        e != NULL ? (unsigned)e->struct_size : 0u, (unsigned)sizeof(sa1_emote));
    }
    if (e->count < 1u || e->count > SA1_EMOTE_MAX_ITEMS) {
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: count %u (1..%u)", (unsigned)e->count,
                        (unsigned)SA1_EMOTE_MAX_ITEMS);
    }
    if (e->flags & ~SA1EM_KNOWN_FLAGS) {
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: unknown flags 0x%X",
                        (unsigned)(e->flags & ~SA1EM_KNOWN_FLAGS));
    }
    if (e->link < -1 || e->link > 120) {
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: link %d (-1 = 8, 0..120)", (int)e->link);
    }
    for (i = 0; i < e->count; i++) {
        const sa1_emote_item *it = &e->items[i];
        if (it->source != SA1_EMOTE_ROW && it->source != SA1_EMOTE_EXTRA && it->source != SA1_EMOTE_EVENT) {
            return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: item %u: source %u", (unsigned)i,
                            (unsigned)it->source);
        }
        if (it->play < SA1_EMOTE_PLAY_DEFAULT || it->play > SA1_EMOTE_PLAY_LOOP) {
            return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: item %u: play %d", (unsigned)i,
                            (int)it->play);
        }
        if (it->play == SA1_EMOTE_PLAY_LOOP && i + 1u != e->count) {
            return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: item %u loops: only the last item may",
                            (unsigned)i);
        }
        if (!(it->speed == 0.0f || (it->speed >= 1.0f / 64.0f && it->speed <= 16.0f))) {
            return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: item %u: speed %g (0 = 1, or 1/64..16)",
                            (unsigned)i, (double)it->speed);
        }
    }
    return SA1_OK;
}

#if !defined(SA1_NO_WORLD)
/* a refusal or warning the world recorded at a pair start since the last call: logged now */
static void sa1em_flush_note(sa1_context *ctx, struct sa1g_world *w)
{
    char why[SA1EM_WHY_MAX];
    if (w != NULL && sa1em_world_take_note(w, why, sizeof why)) {
        sa1_log(ctx, SA1_LOG_WARN, "emote: %s", why);
    }
}
#endif

sa1_status sa1_character_emote(sa1_context *ctx, sa1_character_id id, const sa1_emote *emote)
{
    sa1_status st;
    int32_t kind;
    uint32_t i;
    if (ctx == NULL) {
        return SA1_ERR_INVALID_ARGUMENT;
    }
    if (SA1EM_FOL_GATED && sa1w_character_is_follower(ctx, id)) {
        return sa1_refuse(ctx, SA1_ERR_UNSUPPORTED, SA1_LOG_DEBUG, "followers do not take emotes, faces or orders (0.9.8)");
    }
    st = sa1em_syntax(ctx, emote);
    if (st != SA1_OK) {
        return st;
    }
    if ((emote->flags & SA1_EMOTE_IN_AIR) && sa1w_character_is_follower(ctx, id)) {
        /* round 0.9.9: the player's option; on a follower it would stop a running follower where it is */
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote: SA1_EMOTE_IN_AIR is not for a follower");
    }
    kind = sa1em_kind_of(ctx, id);
    if (kind < 0) {
        return sa1_fail(ctx, SA1_ERR_NOT_FOUND, "sa1_character_emote: no character %d", (int)id);
    }
    if (kind == SA1_CHAR_EGGMAN || kind == SA1_CHAR_TIKAL) {
        return sa1_fail(ctx, SA1_ERR_UNSUPPORTED, "%s has no emote list", sa1em_who(kind, 0));
    }
#if defined(SA1_NO_WORLD)
    for (i = 0; i < emote->count; i++) {
        if (emote->items[i].source == SA1_EMOTE_EVENT) {
            if (sa1ev_entry_of(kind, emote->items[i].index) == NULL) {
                char nm[64];
                sa1em_name(kind, SA1_EMOTE_FORM_NORMAL, &emote->items[i], nm, sizeof nm);
                return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "%s is not available for %s", nm, sa1em_who(kind, 0));
            }
            continue;
        }
        if (sa1em_find(sa1em_list_of(kind, SA1_EMOTE_FORM_NORMAL), emote->items[i].source, emote->items[i].index, NULL) ==
                NULL &&
            sa1em_find(sa1em_list_of(kind, SA1_EMOTE_FORM_SUPER), emote->items[i].source, emote->items[i].index, NULL) ==
                NULL) {
            char nm[64];
            sa1em_name(kind, SA1_EMOTE_FORM_NORMAL, &emote->items[i], nm, sizeof nm);
            return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "%s is not available for %s", nm, sa1em_who(kind, 0));
        }
    }
    return sa1_fail(ctx, SA1_ERR_NOT_IMPLEMENTED, "this libsa1 build has no world core (SA1_NO_WORLD): no emotes");
#else
    {
        struct sa1g_world *w = NULL;
        uint32_t form = SA1_EMOTE_FORM_NORMAL, nev = 0, bytes = 0;
        const sa1em_list *l;
        const sa1em_motion_block *blocks[SA1_EMOTE_MAX_ITEMS];
        char why[SA1EM_WHY_MAX];
        st = sa1w_character_world_ensure(ctx, id, &w);
        if (SA1_FAILED(st) || w == NULL) {
            return SA1_FAILED(st) ? st : SA1_ERR_NOT_LOADED;
        }
        sa1em_flush_note(ctx, w);
        sa1em_world_form(w, &kind, &form);
        l = sa1em_list_of(kind, form);
        memset((void *)blocks, 0, sizeof blocks);
        for (i = 0; i < emote->count; i++) {
            const sa1_emote_item *it = &emote->items[i];
            if (it->source == SA1_EMOTE_EVENT) {
                /* round 100-EV: a cutscene animation, loaded first (sa1_emote_event_load); the normal form only */
                const sa1ev_list *v = l != NULL ? sa1em_events_of(kind, form) : NULL;
                const sa1em_motion_block *b;
                sa1_status bs;
                uint32_t j, dup = 0;
                if (v == NULL || it->index >= v->count) {
                    char nm[64];
                    sa1em_name(kind, form, it, nm, sizeof nm);
                    return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "%s is not available for %s", nm, sa1em_who(kind, form));
                }
                b = sa1ev_block(ctx, kind, it->index, &bs, why, sizeof why);
                if (b == NULL) {
                    if (bs == SA1_ERR_NOT_LOADED) {
                        /* the host loads it and asks again (G-SA1 does this without a visible wait): a normal answer */
                        return sa1_refuse(ctx, SA1_ERR_NOT_LOADED, SA1_LOG_DEBUG, "the cutscene animation %s is not loaded yet",
                                          v->e[it->index].name);
                    }
                    /* review RX.6: the loader kept the reason on its thread; it is reported here, on the game thread */
                    return sa1_fail(ctx, bs, "%s", why[0] ? why : "the cutscene animation cannot be read");
                }
                for (j = 0; j < i; j++) {
                    dup |= blocks[j] == b;
                }
                if (!dup) {
                    bytes += (b->size + 15u) & ~15u;
                }
                blocks[i] = b;
                nev++;
                continue;
            }
            if (sa1em_find(l, it->source, it->index, NULL) == NULL) {
                char nm[64];
                sa1em_name(kind, form, it, nm, sizeof nm);
                return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "%s is not available for %s", nm, sa1em_who(kind, form));
            }
        }
        if (bytes > SA1EM_SLAB_SIZE) {
            return sa1_refuse(ctx, SA1_ERR_LIMIT, SA1_LOG_WARN, "the emote is too long");
        }
        st = sa1em_world_check(w, emote, 0, why, sizeof why);
        if (SA1_FAILED(st)) {
            /* the plain words alone ("in the air", "moving", "the game's memory is full", "... is not available ...").
               Round 0.9.5 (sadc docs/research/board095_perf.md 4): a refusal of the game's state is the call's normal
               answer - logged at DEBUG; the full heap at WARN; any other status (an entry the plan cannot use) stays an
               ERROR. sa1_last_error is the same text in every case */
            if (st == SA1_ERR_UNSUPPORTED) {
                return sa1_refuse(ctx, st, SA1_LOG_DEBUG, "%s", why[0] ? why : "busy");
            }
            if (st == SA1_ERR_LIMIT) {
                return sa1_refuse(ctx, st, SA1_LOG_WARN, "%s", why[0] ? why : "busy");
            }
            return sa1_fail(ctx, st, "%s", why[0] ? why : "busy");
        }
        /* SA1_PARTIAL: the world has not run its first pair (no player, or jvmode not 1 yet): checked at the pair start */
        st = nev ? sa1em_world_latch_ev(ctx, w, emote, st == SA1_PARTIAL, blocks) : sa1em_world_latch(ctx, w, emote, st == SA1_PARTIAL);
        if (st == SA1_ERR_LIMIT) {
            return sa1_refuse(ctx, st, SA1_LOG_WARN, "the emote is too long");
        }
        if (st != SA1_OK) {
            return sa1_fail(ctx, st, "sa1_character_emote: no room for the emote's state in the world");
        }
        return SA1_OK;
    }
#endif
}

sa1_status sa1_character_emote_stop(sa1_context *ctx, sa1_character_id id, uint32_t how)
{
    int32_t kind;
    if (ctx == NULL) {
        return SA1_ERR_INVALID_ARGUMENT;
    }
    if (SA1EM_FOL_GATED && sa1w_character_is_follower(ctx, id)) {
        return sa1_refuse(ctx, SA1_ERR_UNSUPPORTED, SA1_LOG_DEBUG, "followers do not take emotes, faces or orders (0.9.8)");
    }
    if (how != SA1_EMOTE_STOP_NOW && how != SA1_EMOTE_STOP_BLEND) {
        return sa1_fail(ctx, SA1_ERR_INVALID_ARGUMENT, "sa1_character_emote_stop: how %u (0 now, 1 blend)", (unsigned)how);
    }
    kind = sa1em_kind_of(ctx, id);
    if (kind < 0) {
        return sa1_fail(ctx, SA1_ERR_NOT_FOUND, "sa1_character_emote_stop: no character %d", (int)id);
    }
    if (kind == SA1_CHAR_EGGMAN || kind == SA1_CHAR_TIKAL) {
        return sa1_fail(ctx, SA1_ERR_UNSUPPORTED, "%s has no emote list", sa1em_who(kind, 0));
    }
#if defined(SA1_NO_WORLD)
    return sa1_fail(ctx, SA1_ERR_NOT_IMPLEMENTED, "this libsa1 build has no world core (SA1_NO_WORLD): no emotes");
#else
    {
        struct sa1g_world *w = sa1_character_world(ctx, id);
        if (w == NULL) {
            return SA1_OK;      /* no world (yet, or a puppet): nothing plays; a stop never builds one */
        }
        sa1em_flush_note(ctx, w);
        return sa1em_world_stop(ctx, w, how);
    }
#endif
}
