#!/usr/bin/env python3
"""Build the SH-4 interpreter harness (sa1h.exe).

    py -3.12 harness/build.py                    # all src/1st_read/*.c natively (matching code only)
    py -3.12 harness/build.py --non-matching     # also the NON_MATCHING bodies -> build/sa1h_nm.exe
    py -3.12 harness/build.py --files none       # interpreter only
    py -3.12 harness/build.py --files src/1st_read/code_8C052A00.c ...
    py -3.12 harness/build.py --target win64     # 64-bit interpreter-only build -> build/sa1h64.exe
    py -3.12 harness/build.py --non-matching --pc            # the libsa1 configuration -> build/sa1h_nm_pc.exe
    py -3.12 harness/build.py --non-matching --pc --rt       # + the libsa1 runtime (libsa1/src/rt/*.c) natively
    py -3.12 harness/build.py ... --tag NAME     # private build: build/sa1h_NAME.exe, own gen_/obj_ directories
    py -3.12 harness/build.py --non-matching --pc --ga       # GUEST-ARENA build: the ga32 text of tools/pclower.py
                                                             # -> build/sa1h_ga.exe (--rt: + the lowered runtime)

Compiler: zig (py -3.12 -m ziglang cc).  The main target is 32-bit Windows
with the LARGE_ADDRESS_AWARE flag set after linking, so that the Dreamcast
RAM can be mapped at 0x8C000000 and guest addresses equal host addresses.

--pc compiles the decompiled code (and --rt the runtime) with the one PC flag
set of tools/pc_cflags.txt, the file libsa1 reads too.  --ga compiles, instead
of the decompiled sources, their GUEST-ARENA lowering (tools/pclower.py
--profile ga32: identity decode, guest == host at 0x8C000000) with the glue of
harness/tools/gen_ga.py; indirect calls go through sa1_fn and the harness's
routing, so lowered code is routed into traces like the plain native code
(docs/libsa1_integration.md 2.3, rung V1).  The FSCA table the
interpreter uses (libsa1/src/rt/rt_fsca_q.c, generated by
harness/tools/dump_fsca.py) is compiled into every build.

Every 32-bit Windows build also compiles the round-5 host-object oracle
(trace --hostobj, src/ho_oracle.c): libsa1's own host-object layer
(libsa1/src/sa1_hostobj.c, libsa1/src/world/sa1_world_hostobj.c, unchanged)
with src/ho_lib_glue.c, in libsa1's world flags (LIB_HOSTOBJ_FLAGS below).
"""
import argparse
import concurrent.futures
import glob
import hashlib
import os
import struct
import subprocess
import sys

HARNESS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HARNESS)
SRC = os.path.join(HARNESS, "src")
ZIG = [sys.executable, "-m", "ziglang", "cc"]
LIB = os.path.join(os.path.dirname(ROOT), "libsa1")
LIB_RT = os.path.join(LIB, "src", "rt")
FSCA_TABLE = os.path.join(LIB_RT, "rt_fsca_q.c")
PC_CFLAGS = os.path.join(ROOT, "tools", "pc_cflags.txt")

HARNESS_SOURCES = ["sh4_cpu.c", "sh4_mem.c", "sh4_call.c", "sh4_sym.c", "sh4_intrin.c", "sh4_fsca_ref.c", "hle.c",
                   "main.c", "t_selftest.c", "t_rtlib.c", "t_leaf.c", "t_diff.c", "t_tools.c", "t_boot.c",
                   "t_sim.c", "pc_runtime.c", "ho_oracle.c"]
# the round-5 host-object oracle (trace --hostobj): libsa1's own layer, unchanged, and its glue (32-bit Windows only)
LIB_HOSTOBJ_SOURCES = [os.path.join(LIB, "src", "sa1_hostobj.c"), os.path.join(LIB, "src", "world", "sa1_world_hostobj.c"),
                       os.path.join(SRC, "ho_lib_glue.c")]
LIB_HOSTOBJ_DEPS = [os.path.join(LIB, "include"), os.path.join(LIB, "src"), os.path.join(LIB, "src", "world")]
COMMON = ["-O2", "-g", "-ffp-contract=off", "-fno-strict-aliasing", "-fwrapv"]
X86 = ["-msse2", "-mfpmath=sse"]
TARGETS = {"win32": "x86-windows-gnu", "win64": "x86_64-windows-gnu", "linux32": "x86-linux-gnu",
           "linux64": "x86_64-linux-gnu"}
ARCH = {"win32": "x86", "linux32": "x86", "win64": "x86_64", "linux64": "x86_64"}

# headers outside harness/src that the harness sources and the runtime
# include (a change rebuilds those objects)
DEP_HEADERS = [os.path.join(ROOT, "include", "pc"), LIB_RT]


def read_pc_cflags(arch, path=PC_CFLAGS):
    """tools/pc_cflags.txt -> flag list for arch ("x86" = 32-bit, "x86_64").
    One flag per line, '#' starts a comment; a line "[x86 x86_64]" restricts
    the flags below it to those architectures, "[all]" lifts the restriction."""
    flags, archs = [], None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if line.startswith("[") and line.endswith("]"):
                names = line[1:-1].split()
                archs = None if names == ["all"] else set(names)
                continue
            if archs is None or arch in archs:
                flags += line.split()
    return flags


def harness_cflags(target_key, extra_inc=()):
    """flags of the harness's own sources (also used by tools/dump_fsca.py)"""
    x86 = X86 if ARCH[target_key] == "x86" else []
    inc = []
    for d in list(extra_inc) + [os.path.join(ROOT, "include")]:
        inc += ["-I", d]
    return ["-target", TARGETS[target_key]] + COMMON + x86 + [
        "-fno-math-errno", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Wno-missing-field-initializers",
        "-I", SRC] + inc


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    return r.returncode, (r.stdout + r.stderr)


def compile_one(args):
    src, obj, flags = args[:3]
    stamp = obj + ".cmd"
    key = hashlib.sha1(" ".join(flags).encode()).hexdigest()
    deps = [src] + [os.path.join(SRC, h) for h in os.listdir(SRC) if h.endswith(".h")]
    if len(args) > 3 and args[3]:
        for d in DEP_HEADERS:
            deps += glob.glob(os.path.join(d, "*.h"))
    for d in (args[4] if len(args) > 4 else ()):
        deps += glob.glob(os.path.join(d, "*.h"))
    if os.path.exists(obj) and os.path.exists(stamp) and open(stamp).read() == key:
        t = os.path.getmtime(obj)
        if all(os.path.getmtime(d) <= t for d in deps if os.path.exists(d)):
            return src, 0, ""
    rc, out = run(ZIG + flags + ["-c", src, "-o", obj])
    if rc == 0:
        open(stamp, "w").write(key)
    return src, rc, out


def set_laa(exe):
    b = bytearray(open(exe, "rb").read())
    e = struct.unpack_from("<I", b, 0x3C)[0]
    off = e + 4 + 18
    struct.pack_into("<H", b, off, struct.unpack_from("<H", b, off)[0] | 0x0020)
    open(exe, "wb").write(b)


def main():
    """Build; decompiled files that fail to compile or link (e.g. half-written
    files of a concurrent decompilation batch) are excluded and the build is
    retried, so the harness itself always builds."""
    a = parse_args()
    auto = set()
    for attempt in range(8):
        rc, bad = build(a, auto)
        if rc == 0:
            if auto:
                print("note: excluded because they did not compile/link: " + ", ".join(sorted(auto)))
            return 0
        bad = set(bad) - auto
        if not bad:
            return 1
        print("excluding %s (does not compile/link now), retrying" % ", ".join(sorted(bad)))
        auto |= bad
    return 1


def parse_args():
    ap = argparse.ArgumentParser()
    ap.add_argument("--files", nargs="*", default=["all"])
    ap.add_argument("--exclude", nargs="*", default=[])
    ap.add_argument("--non-matching", action="store_true")
    ap.add_argument("--target", default="win32", choices=sorted(TARGETS))
    ap.add_argument("--out")
    ap.add_argument("--tag", help="private build directories and exe name (harness/build/sa1h_<tag>.exe), "
                                  "so several builds (e.g. one per agent) can run at the same time")
    ap.add_argument("--no-fma", action="store_true", help="do not contract a*b+c into FMA in decompiled code")
    ap.add_argument("--pc", action="store_true",
                    help="compile the decompiled code as libsa1 does, with the flags of tools/pc_cflags.txt: "
                         "-DTARGET_PC, no FP contraction (fused only where the source says SA1_FMAC); "
                         "build/sa1h[_nm]_pc.exe. -DNON_MATCHING from the file applies with --non-matching only")
    ap.add_argument("--rt", action="store_true",
                    help="also compile the libsa1 runtime (libsa1/src/rt/*.c) natively like decompiled code: "
                         "functions named like SDK symbols (njSin ...) get adapters at their SDK addresses, so "
                         "'diff njSin' compares them with the original SDK code and --route runs them in traces; "
                         "implies --pc; build/sa1h[_nm]_pc_rt.exe")
    ap.add_argument("--ga", action="store_true",
                    help="compile the GUEST-ARENA lowering of the decompiled code (tools/pclower.py, profile ga32) "
                         "with the glue of harness/tools/gen_ga.py instead of the sources; implies --non-matching "
                         "--pc; build/sa1h_ga[_rt].exe")
    ap.add_argument("-j", type=int, default=os.cpu_count() or 4)
    return ap.parse_args()


def build(a, auto_exclude):

    native = a.target == "win32"
    if a.rt:
        a.pc = True
    if a.ga:
        if not native:
            print("--ga needs the 32-bit Windows target (guest == host)")
            return 1, set()
        a.pc = True
        a.non_matching = True
    files = a.files if native else ["none"]
    if files == ["none"]:
        files = []
    # the runtime: every libsa1/src/rt/*.c but the FSCA table, which every
    # build compiles as a harness source (the interpreter uses it)
    rt_files = []
    if a.rt and native:
        rt_files = sorted(f for f in glob.glob(os.path.join(LIB_RT, "*.c"))
                          if os.path.normcase(os.path.abspath(f)) != os.path.normcase(os.path.abspath(FSCA_TABLE)))
    if not os.path.exists(FSCA_TABLE):
        print("missing %s: generate it with py -3.12 harness/tools/dump_fsca.py" % FSCA_TABLE)
        return 1, set()
    tag = a.target + ("_nm" if a.non_matching else "") + ("_pc" if a.pc else "") + ("_rt" if a.rt else "") + \
        ("" if a.files == ["all"] and not a.exclude else "_custom")
    if a.ga:
        tag = a.target + "_ga" + ("_rt" if a.rt else "") + ("" if a.files == ["all"] and not a.exclude else "_custom")
    if a.tag:
        tag = "tag_" + a.tag
    build = os.path.join(HARNESS, "build")
    gen = os.path.join(build, "gen_" + tag)
    objd = os.path.join(build, "obj_" + tag)
    os.makedirs(gen, exist_ok=True)
    os.makedirs(objd, exist_ok=True)
    if a.tag and not a.out:
        a.out = os.path.join(build, "sa1h_%s%s" % (a.tag, ".exe" if a.target.startswith("win") else ""))
    exe = a.out or os.path.join(build, {"win32": "sa1h", "win64": "sa1h64", "linux32": "sa1h_linux32",
                                        "linux64": "sa1h_linux64"}[a.target] + ("_nm" if a.non_matching else "") +
                                 ("_pc" if a.pc else "") + ("_rt" if a.rt else "") +
                                 (".exe" if a.target.startswith("win") else ""))
    if a.ga and not a.out and not a.tag:
        exe = os.path.join(build, "sa1h_ga" + ("_rt" if a.rt else "") + ".exe")

    # 1. generated sources
    rc, out = run([sys.executable, os.path.join(HARNESS, "tools", "gen_optab.py"), os.path.join(gen, "sh4_optab.h")])
    print(out.strip())
    if rc:
        return 1, set()
    if a.ga:
        rc = ga_generate(a, gen, files, rt_files, auto_exclude)
        if rc:
            return 1, set()
    else:
        cmd = [sys.executable, os.path.join(HARNESS, "tools", "gen_native.py"), "--out", gen]
        if a.non_matching:
            cmd.append("--non-matching")
        if a.pc:
            cmd.append("--pc")
        if rt_files:
            cmd += ["--inc", LIB_RT]
        for x in list(a.exclude) + sorted(auto_exclude):
            cmd += ["--exclude", x]
        cmd += [os.path.join(ROOT, f) if f != "all" else f for f in files]
        cmd += rt_files
        rc, out = run(cmd)
        print(out.strip())
        if rc:
            return 1, set()

    # 2. compile
    target = ["-target", TARGETS[a.target]]
    x86 = X86 if a.target in ("win32", "linux32") else []
    hflags = harness_cflags(a.target, [gen])
    # decompiled code: SHC fuses a*b+c into FMAC (one rounding); with FMA3 and
    # contraction clang does the same for the same expressions (--no-fma to
    # get separately rounded products, i.e. plain SSE2)
    fma = [] if a.no_fma or a.target not in ("win32", "linux32") else ["-mfma", "-ffp-contract=on"]
    harness_side = ["-w", "-Wno-error=implicit-function-declaration", "-Wno-error=implicit-int",
                    "-include", os.path.join(SRC, "harness_pre.h"),
                    "-I", os.path.join(ROOT, "include"), "-I", os.path.join(ROOT, "src"),
                    "-I", os.path.join(ROOT, "src", "1st_read")]
    if rt_files:
        harness_side += ["-I", LIB_RT]
    if a.pc:
        # libsa1: the one PC flag set (tools/pc_cflags.txt): nothing is
        # contracted; SA1_FMAC marks the original's FMAC sites.  The matching
        # bodies stay selectable for A/B checks (--pc without --non-matching).
        pcf = read_pc_cflags(ARCH[a.target])
        if not a.non_matching:
            pcf = [f for f in pcf if f != "-DNON_MATCHING"]
        dflags = target + ["-g"] + pcf + harness_side
    else:
        dflags = target + COMMON + x86 + fma + ["-frounding-math", "-fno-builtin"] + harness_side
        if a.non_matching:
            dflags.append("-DNON_MATCHING")
    jobs = []
    # the host-object oracle: libsa1's public header for ho_oracle.c; libsa1's world flags for its layer (sadc's
    # include/ for sa1/guest.h and pc/sh4_fpmodel.h), profile ga32 (guest == host), and renames that keep it off the
    # GUEST-ARENA glue of --ga builds (sa1_fn, sa1g_sqrtf, sa1g_fsca: ho_lib_glue.c)
    ho_on = a.target == "win32"
    ho_defs = ["-DSA1_STATIC", "-DSA1_GA32"] + (["-DSA1H_HOSTOBJ"] if ho_on else [])
    lib_ho_flags = target + ["-std=gnu11", "-O2", "-g", "-ffp-contract=off", "-frounding-math", "-fno-builtin"] + \
        x86 + ["-I", os.path.join(LIB, "include"), "-I", os.path.join(LIB, "src"), "-I", os.path.join(LIB, "src", "world"),
               "-I", os.path.join(ROOT, "include"), "-I", SRC] + ho_defs + \
        ["-Dsa1_fn=sa1h_ho_fn", "-Dsa1g_sqrtf=sa1h_ho_sqrtf", "-Dsa1g_fsca=sa1h_ho_fsca", "-Wno-unused-function"]
    for s in HARNESS_SOURCES:
        f = hflags
        if a.ga and a.rt and s == "pc_runtime.c":
            # the lowered runtime defines sa1_tmu (pcdata) and sa1_tmu_tcnt1 itself
            f = hflags + ["-Dsa1_tmu=sa1h_pc_tmu", "-Dsa1_tmu_tcnt1=sa1h_pc_tmu_tcnt1"]
        if s == "ho_oracle.c":
            f = hflags + ["-I", os.path.join(LIB, "include")] + ho_defs + ["-Wno-unused-function",
                                                                          "-Wno-unused-variable"]
            jobs.append((os.path.join(SRC, s), os.path.join(objd, s[:-2] + ".o"), f, True, LIB_HOSTOBJ_DEPS))
            continue
        jobs.append((os.path.join(SRC, s), os.path.join(objd, s[:-2] + ".o"), f, True))
    if ho_on:
        for s in LIB_HOSTOBJ_SOURCES:
            jobs.append((s, os.path.join(objd, "hostobj_" + os.path.basename(s)[:-2] + ".o"), lib_ho_flags, True,
                         LIB_HOSTOBJ_DEPS))
    jobs.append((FSCA_TABLE, os.path.join(objd, "rt_fsca_q.o"), hflags, True))
    for s in ("overlays.c", "functions.c", "native_abs.c", "native_thunks.c", "native_registry.c"):
        jobs.append((os.path.join(gen, s), os.path.join(objd, s[:-2] + ".o"), hflags))
    nsrc = os.path.join(gen, "native_src")
    if a.ga:
        # the lowered text: the PC flag set, profile ga32, no harness pre-include (it is self-contained)
        nsrc = os.path.join(gen, "ga_src")
        dflags = target + ["-g"] + read_pc_cflags(ARCH[a.target]) + ["-DSA1_GA32", "-w",
                                                                      "-I", os.path.join(ROOT, "include")]
        gflags = hflags + ["-DSA1_GA32", "-Wno-unused-function"]
        for s, extra in (("ga_glue.c", []), ("sa1g_fntab.c", ["-DSA1G_FN_HOST"]), ("sa1g_pcdata.c", [])):
            jobs.append((os.path.join(gen, s), os.path.join(objd, s[:-2] + ".o"), gflags + extra))
    for s in sorted(os.listdir(nsrc)) if os.path.isdir(nsrc) else []:
        if s.endswith(".c"):
            is_rt = any(os.path.basename(f) == s for f in rt_files)
            jobs.append((os.path.join(nsrc, s), os.path.join(objd, "decomp_" + s[:-2] + ".o"), dflags,
                         is_rt or a.ga))
    failed = False
    bad = set()
    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        for src, rc, out in ex.map(compile_one, jobs):
            if rc:
                if os.path.dirname(os.path.abspath(src)) == os.path.abspath(nsrc):
                    bad.add(os.path.basename(src))
                    print("compile failed (decompiled file, will be excluded): %s\n%s" % (src, out[-1500:]))
                else:
                    failed = True
                    print("compile failed: %s\n%s" % (src, out))
            elif out.strip():
                print(out.strip())
    if failed or bad:
        return 1, bad
    objs = [j[1] for j in jobs]
    # the object list exceeds the Windows command-line limit: pass it in a response file
    rsp = os.path.join(objd, "link.rsp")
    with open(rsp, "w", encoding="utf-8") as f:
        for o in objs:
            f.write('"%s"\n' % os.path.abspath(o).replace("\\", "/"))
    link = ZIG + target + ["-g", "-o", exe, "@" + rsp]
    if a.target.startswith("linux"):
        link.append("-lm")
    rc, out = run(link)
    if rc:
        print("link failed:\n" + out)
        import re
        return 1, set(re.findall(r"(?:native_src|ga_src)[\\/]+(\w+\.c)", out))
    if a.target == "win32":
        set_laa(exe)
    print("built %s (%d objects)" % (exe, len(objs)))
    return 0, set()


def ga_generate(a, gen, files, rt_files, auto_exclude):
    """--ga: lower the sources (tools/pclower.py --profile ga32, once per build.py run) and generate the
    harness glue (harness/tools/gen_ga.py); returns 0 on success"""
    pdir = os.path.join(gen, "pclower")
    if not getattr(a, "_ga_lowered", False):
        if files == ["all"]:
            d = os.path.join(ROOT, "src", "1st_read")
            srcs = sorted(os.path.join(d, x) for x in os.listdir(d) if x.endswith(".c"))
        else:
            srcs = [os.path.join(ROOT, f) for f in files]
        excl = {os.path.basename(x) for x in a.exclude}
        srcs = [f for f in srcs if os.path.basename(f) not in excl]
        cmd = [sys.executable, os.path.join(ROOT, "tools", "pclower.py"), "--profile", "ga32", "--out", pdir,
               "--extern-unresolved", "--no-layout", "--drop-failing", "-j", str(a.j)]
        if rt_files:
            cmd += ["--inc", LIB_RT]
        # the source list exceeds the Windows command-line limit: pclower reads it from a response file
        os.makedirs(gen, exist_ok=True)
        rsp = os.path.join(gen, "pclower_tus.rsp")
        with open(rsp, "w", encoding="utf-8") as f:
            for x in srcs + list(rt_files):
                f.write(os.path.abspath(x) + "\n")
        rc, out = run(cmd + ["@" + rsp])
        print("\n".join(out.strip().splitlines()[-40:]))
        if rc:
            print("pclower failed (R8 is fail-closed: fix the errors above, or exclude the files with --exclude)")
            return 1
        a._ga_lowered = True
    cmd = [sys.executable, os.path.join(HARNESS, "tools", "gen_ga.py"), "--pclower", pdir, "--out", gen]
    if rt_files:
        cmd.append("--rt")
    for x in list(a.exclude) + sorted(auto_exclude):
        cmd += ["--exclude", x]
    rc, out = run(cmd)
    print(out.strip())
    return rc


if __name__ == "__main__":
    sys.exit(main())