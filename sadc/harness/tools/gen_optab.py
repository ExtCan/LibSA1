#!/usr/bin/env python3
"""Generate the SH-4 opcode -> handler table for the harness interpreter.

The table is derived from tools/sh4/isa.py (validated against asmsh on all
65,536 encodings), so the interpreter decodes exactly what the project's
disassembler decodes.  Every valid word is mapped to one handler id named
after its normalised instruction form (mnemonic + operand shape); invalid
words map to OP_ILLEGAL (0).

    py -3.12 harness/tools/gen_optab.py <out.h>

The generated header defines:
    enum sh4_op { OP_ILLEGAL, OP_ADD_I_R, ... , OP_COUNT };
    static const uint8_t sh4_optab[65536];
    static const char *const sh4_opname[OP_COUNT];   (normalised form)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from sh4.isa import decode  # noqa: E402


def shape_of(insn):
    shape = []
    for o in insn.ops:
        k = o[0]
        if k == "reg":
            t = o[1]
            t = re.sub(r"^R\d+_BANK$", "Rb", t)
            t = re.sub(r"^R\d+$", "R", t)
            t = re.sub(r"^FR\d+$", "F", t)
            t = re.sub(r"^DR\d+$", "D", t)
            t = re.sub(r"^FV\d+$", "V", t)
            shape.append(t)
        elif k == "mem":
            t = o[1]
            t = re.sub(r"\(\d+,", "(d,", t)
            t = re.sub(r"(?<!\()R\d+", "R", t)
            shape.append(t)
        elif k == "imm":
            shape.append("#")
        elif k == "pcrel":
            shape.append("pc%d" % o[1])
        elif k == "branch":
            shape.append("lbl")
    return insn.mnem + (" " + ",".join(shape) if shape else "")


def enum_name(key):
    s = key
    for a, b in (("@(d,GBR)", "DGBR"), ("@(R0,GBR)", "R0GBR"), ("@(R0,R)", "R0R"),
                 ("@(d,R)", "DR"), ("@R+", "RP"), ("@-R", "MR"), ("@R", "AR"),
                 ("#", "I"), ("pc4", "PC"), ("pc2", "PC"), ("pc0", "PC"), (" lbl", ""),
                 ("XMTRX", "X")):
        s = s.replace(a, b)
    s = s.replace(".", "_").replace("/", "_").replace(",", "_").replace(" ", "_")
    return "OP_" + s


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "build", "gen", "sh4_optab.h")
    forms = {}
    table = [None] * 65536
    for w in range(65536):
        insn = decode(w, 0x8C000000)
        if insn is None:
            continue
        key = shape_of(insn)
        forms.setdefault(key, []).append(w)
        table[w] = key
    # every form must be one fixed bit pattern (handlers decode fields themselves)
    patterns = {}
    for key, words in forms.items():
        a, o = 0xFFFF, 0
        for w in words:
            a &= w
            o |= w
        fixed = ~(a ^ o) & 0xFFFF
        patterns[key] = "".join(("1" if (a >> b) & 1 else "0") if (fixed >> b) & 1 else "x"
                                for b in range(15, -1, -1))
    keys = sorted(forms)
    names = [enum_name(k) for k in keys]
    assert len(set(names)) == len(names), "enum name collision"
    ids = {k: i + 1 for i, k in enumerate(keys)}
    assert len(keys) + 1 < 256
    lines = []
    lines.append("/* Generated by harness/tools/gen_optab.py from tools/sh4/isa.py. Do not edit. */")
    lines.append("#ifndef SH4_OPTAB_H")
    lines.append("#define SH4_OPTAB_H")
    lines.append("#include <stdint.h>")
    lines.append("enum sh4_op {")
    lines.append("    OP_ILLEGAL = 0,")
    for k, n in zip(keys, names):
        lines.append("    %s = %d, /* %-22s %s (%d words) */" % (n, ids[k], k, patterns[k], len(forms[k])))
    lines.append("    OP_COUNT = %d" % (len(keys) + 1))
    lines.append("};")
    lines.append("static const char *const sh4_opname[OP_COUNT] = {")
    lines.append('    "(illegal)",')
    for k in keys:
        lines.append('    "%s",' % k)
    lines.append("};")
    lines.append("static const uint8_t sh4_optab[65536] = {")
    for base in range(0, 65536, 32):
        row = ",".join(str(ids[table[w]] if table[w] else 0) for w in range(base, base + 32))
        lines.append("    " + row + ",")
    lines.append("};")
    lines.append("#endif")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("gen_optab: %d forms, %d valid encodings -> %s" % (len(keys), sum(len(v) for v in forms.values()), out))


if __name__ == "__main__":
    main()