#!/usr/bin/env python3
"""Generate the native side of the harness GUEST-ARENA build (harness/build.py --ga) from the
ga32 output of tools/pclower.py (docs/libsa1_integration.md 2.3 and 9.1 rung V1).

The lowered text (profile ga32: identity decode, guest == host at 0x8C000000) replaces the
decompiled sources of the plain native build; this script plays gen_native.py's part for it:

  ga_src/*.c          the lowered TUs that the harness can link (copies; a TU whose calls of one
                      external function disagree in ABI class with other TUs gets a #define to its own
                      thunk variant, like gen_native's per-file renames)
  native_thunks.c     one thunk per external function (called by name or address-taken, not lowered
                      here): marshals the call to the SHC ABI and runs the original through sh4_invoke
  native_registry.c   sh4_native_fns[] (lowered functions: guest address, guest-regs -> native adapter),
                      sh4_thunks[], sh4_native_datas[]
  native_abs.c        empty (lowered code reaches globals through SA1_GV, no absolute symbols)
  sa1g_fntab.c        the code map of the included TUs (compiled with -DSA1G_FN_HOST)
  sa1g_pcdata.c       the R4 pcdata units of the included TUs
  ga_glue.c           sa1_fn (routing), the GA fault entry points, the rt symbols the lowered code
                      needs (intrinsics, sa1_rt_xmtrx, host data such as sa1_tmu), pcdata initialisation
  overlays.c, functions.c, ga_manifest.json

Routing: sa1_fn() returns the DC code address itself. Native code calling it takes the DEP fault the
plain native build takes for guest function pointers, and harness/src/sh4_call.c sends the call to the
routed native function (trace --route / --route-only) or runs the original in the interpreter, with
the signature of sh4_native_fns / sh4_thunks. So lowered code is routed into traces exactly like the
unlowered code.

Overlay images (harness/build.py --ga --files ... src/overlays/<dir>/*.c): pclower names an overlay
TU's functions <IMAGE>__<name> and records the unit's image; the registry records every native
function's image and the image guard tables (gen_native.emit_image_guard, harness/src/image_guard.h),
so the trace command routes an overlay function only while its image is the one loaded.

    py -3.12 harness/tools/gen_ga.py --pclower DIR --out GEN [--exclude FILE]...
"""
import argparse
import bisect
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HARNESS = os.path.dirname(HERE)
ROOT = os.path.dirname(HARNESS)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gen_native as gn  # noqa: E402
import pclower as pcl    # noqa: E402

# runtime functions the harness provides (ga_glue.c forwards to harness/src/sh4_intrin.c; pc_runtime.c)
HARNESS_RT_FUNCS = {"sa1g_fabsf", "sa1g_sqrtf", "sa1g_fsrra", "sa1g_fipr", "sa1g_ftrv", "sa1g_fsca",
                    "sa1g_set_cr", "sa1g_get_cr", "sa1g_set_imask", "sa1g_get_imask", "sa1g_set_gbr",
                    "sa1g_get_gbr", "njFraction", "sa1_tmu_tcnt1", "sa1g_fatal"}
# (not sa1_rt_pad: libsa1/src/rt/rt_input.c's libsa1 profile reads the world's pad latch; in the harness
# pdGetPeripheral must stay the original behind the simulator's pad HLE, so that TU is excluded)
HARNESS_RT_DATA = {"sa1_rt_xmtrx", "sh4_fsca_q", "xm"}
# PC-only data that harness/src/pc_runtime.c defines natively: exported to the lowered code as pcdata
HARNESS_PCDATA = {"sa1_tmu"}
# fixed ABI classes of the sa1/guest.h runtime names (their game declarations may be inactive)
R7_SIGS = pcl.R7_SIGS

INT_CT = {"i8": "signed char", "u8": "unsigned char", "i16": "short", "u16": "unsigned short", "i32": "int32_t",
          "u32": "uint32_t", "p": "void *", "f32": "float", "f64": "double", "v": "void", "gfn": "sa1_gfn"}
OK_CLASSES = {"v", "i8", "u8", "i16", "u16", "i32", "u32", "p", "f32", "f64", "gfn"}

HDR = """/* Generated by harness/tools/gen_ga.py. Do not edit. */
#include "sh4.h"
#include <stdarg.h>
#include <stdint.h>
typedef struct sa1_gfn { uint32_t v; } sa1_gfn;
"""


def parse_sig(sig):
    """'ret:a,b,...' -> (ret, [params], variadic); None for '?'"""
    if not sig or sig == "?":
        return None
    ret, _, ps = sig.partition(":")
    params = [p for p in ps.split(",") if p] if ps else []
    variadic = bool(params) and params[-1] == "..."
    if variadic:
        params = params[:-1]
    return ret, params, variadic


def harness_sig(sig):
    """registry signature string (sh4_sig_parse): gfn is a 32-bit integer word"""
    s = parse_sig(sig)
    if s is None:
        return "u32:"
    ret, params, variadic = s
    m = lambda c: "u32" if c == "gfn" else c       # noqa: E731
    return m(ret) + ":" + ",".join([m(p) for p in params] + (["..."] if variadic else []))


def emit_thunk(name, guest, sig):
    s = parse_sig(sig)
    lines = ["/* %s %08X: %s */" % (name, guest, sig)]
    if s is None:
        # unprototyped: four integer words, like gen_native
        lines += ["uint32_t %s(uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3)" % name, "{",
                  "    sh4_arg A_[4];", "    uint32_t r0_ = 0; float f0_ = 0.0f;",
                  "    A_[0] = sh4_ai(a0); A_[1] = sh4_ai(a1); A_[2] = sh4_ai(a2); A_[3] = sh4_ai(a3);",
                  "    sh4_invoke(0x%08Xu, A_, 4, &r0_, &f0_);" % guest, "    (void)f0_;", "    return r0_;", "}"]
        return "\n".join(lines)
    ret, params, variadic = s
    if ret not in OK_CLASSES or any(p not in OK_CLASSES or p == "v" for p in params):
        lines.append("void %s(void) { sh4_unsupported_call(\"%s\", 0x%08Xu); }" % (name, name, guest))
        return "\n".join(lines)
    # integer arguments are taken as the raw 32-bit stack slots the caller pushed (the caller has
    # extended them per its own prototype, which is what the original's caller did too)
    ct = []
    for i, p in enumerate(params):
        ct.append("%s a%d" % ({"f32": "float", "f64": "double", "gfn": "sa1_gfn"}.get(p, "uint32_t"), i))
    decl = ", ".join(ct) + (", ..." if variadic and ct else ("..." if variadic else ""))
    lines.append("%s %s(%s)" % (INT_CT[ret], name, decl or "void"))
    lines.append("{")

    def conv(p, a):
        if p == "f32":
            return "sh4_af(%s)" % a
        if p == "f64":
            return "sh4_af((float)%s)" % a
        if p == "gfn":
            return "sh4_ai(%s.v)" % a
        return "sh4_ai(%s)" % a
    if variadic:
        lines.append("    uint32_t w_[32]; int n_ = 0, i_; uint32_t r0_ = 0; float f0_ = 0.0f;")
        lines.append("    va_list ap_;")
        for i, p in enumerate(params):
            lines.append("    w_[n_++] = %s.v;" % conv(p, "a%d" % i))
        if params:
            lines.append("    va_start(ap_, a%d);" % (len(params) - 1))
            lines.append("    for (i_ = 0; i_ < 8; i_++) w_[n_++] = va_arg(ap_, uint32_t);")
            lines.append("    va_end(ap_);")
        lines.append("    sh4_invoke_varargs(0x%08Xu, w_, n_, &r0_);" % guest)
        lines.append("    f0_ = SH4.fr.f[0];")
    else:
        lines.append("    sh4_arg A_[%d];" % max(1, len(params)))
        lines.append("    uint32_t r0_ = 0; float f0_ = 0.0f;")
        for i, p in enumerate(params):
            lines.append("    A_[%d] = %s;" % (i, conv(p, "a%d" % i)))
        lines.append("    sh4_invoke(0x%08Xu, A_, %d, &r0_, &f0_);" % (guest, len(params)))
    lines.append("    (void)r0_; (void)f0_;")
    if ret == "f32":
        lines.append("    return f0_;")
    elif ret == "f64":
        lines.append("    return (double)f0_;")
    elif ret == "gfn":
        lines.append("    { sa1_gfn g_; g_.v = r0_; return g_; }")
    elif ret == "p":
        lines.append("    return (void *)(uintptr_t)r0_;")
    elif ret != "v":
        lines.append("    return (%s)r0_;" % INT_CT[ret])
    lines.append("}")
    return "\n".join(lines)


def adapter_ok(sig):
    s = parse_sig(sig)
    if s is None:
        return False
    ret, params, variadic = s
    return not variadic and ret in OK_CLASSES and all(p in OK_CLASSES and p != "v" for p in params)


def emit_adapter(name, sig):
    ret, params, variadic = parse_sig(sig)
    places = gn.guest_arg_regs(["f32" if p in ("f32", "f64") else "i32" for p in params])
    lines = ["extern %s %s(%s);" % (INT_CT[ret], name, ", ".join(INT_CT[p] for p in params) or "void"),
             "static void adapt_%s(sh4_cpu *c)" % name, "{"]
    args = []
    for p, (kind, n) in zip(params, places):
        src = "c->r[%d]" % n if kind == "r" else ("c->fr.u[%d]" % n if kind == "f" else
                                                    "sh4_read32(c->r[15] + %du)" % (4 * n))
        if p == "f32":
            args.append("sh4_u2f(%s)" % src)
        elif p == "f64":
            args.append("(double)sh4_u2f(%s)" % src)
        elif p == "p":
            args.append("(void *)(uintptr_t)%s" % src)
        elif p == "gfn":
            args.append("sa1g_gfn_of(%s)" % src)
        else:
            args.append("(%s)%s" % (INT_CT[p], src))
    call = "%s(%s)" % (name, ", ".join(args))
    if ret == "v":
        lines.append("    %s;" % call)
    elif ret == "f32":
        lines.append("    c->fr.f[0] = %s;" % call)
    elif ret == "f64":
        lines.append("    c->fr.f[0] = (float)%s;" % call)
    elif ret == "p":
        lines.append("    c->r[0] = (uint32_t)(uintptr_t)%s;" % call)
    elif ret == "gfn":
        lines.append("    c->r[0] = %s.v;" % call)
    elif ret in ("i8", "i16", "i32"):
        lines.append("    c->r[0] = (uint32_t)(int32_t)%s;" % call)
    else:
        lines.append("    c->r[0] = (uint32_t)%s;" % call)
    if not params:
        lines.append("    (void)c;")
    lines.append("}")
    return "\n".join(lines)


GLUE = r'''/* Generated by harness/tools/gen_ga.py. Do not edit.
 * Host side of the lowered (GUEST-ARENA, profile ga32) code inside the harness. */
#include "pc/sh4_fpmodel.h"
#include "sh4.h"
#include "sa1/guest.h"

/* R5: the harness routes indirect calls itself. The DC code address is called as is: guest RAM is
 * not executable, so the call faults into sh4_call.c's DEP handler, which jumps to the routed native
 * function or runs the original in the interpreter (signature from sh4_native_fns / sh4_thunks),
 * exactly as for guest function pointers called by the unlowered native code. */
void *sa1_fn(sa1_gfn g, uint32_t sig)
{
    (void)sig;
    return (void *)(uintptr_t)g.v;
}

/* GA world faults -> harness faults (ga32 never encodes out of range; stubs are not linked) */
void sa1g_fault_encode(const void *host)
{
    sh4_fault(&SH4, SH4_FAULT_HOOK, (uint32_t)(uintptr_t)host, "GA: encode of host address %p", host);
    for (;;) {
    }
}

void sa1g_fault_fn(uint32_t g, uint32_t sig)
{
    sh4_fault(&SH4, SH4_FAULT_HOOK, g, "GA: code-map fault at %08X (signature %08X)", g, sig);
    for (;;) {
    }
}

void sa1g_unimpl(uint32_t g, const char *name)
{
    sh4_fault(&SH4, SH4_FAULT_HOOK, g, "GA: unimplemented %s (%08X)", name, g);
    for (;;) {
    }
}

/* R7 runtime functions: the harness's SHC intrinsics (sh4_intrin.c), the interpreter's models */
float _builtin_fabsf(float x);
float _builtin_sqrtf(float x);
float _builtin_fsrra(float x);
float _builtin_fipr(float *a, float *b);
void _builtin_ftrv(float *v, float *out);
void _builtin_fsca(long ang, float *s, float *c);
void _builtin_set_cr(int cr);
int _builtin_get_cr(void);
void _builtin_set_imask(int mask);
int _builtin_get_imask(void);
void _builtin_set_gbr(void *p);
void *_builtin_get_gbr(void);

float sa1g_fabsf(float x) { return _builtin_fabsf(x); }
float sa1g_sqrtf(float x) { return _builtin_sqrtf(x); }
float sa1g_fsrra(float x) { return _builtin_fsrra(x); }
float sa1g_fipr(float *a, float *b) { return _builtin_fipr(a, b); }
void sa1g_ftrv(float *v, float *out) { _builtin_ftrv(v, out); }
void sa1g_fsca(int32_t ang, float *s, float *c) { _builtin_fsca((long)ang, s, c); }
void sa1g_set_cr(int cr) { _builtin_set_cr(cr); }
int sa1g_get_cr(void) { return _builtin_get_cr(); }
void sa1g_set_imask(int mask) { _builtin_set_imask(mask); }
int sa1g_get_imask(void) { return _builtin_get_imask(); }
void sa1g_set_gbr(void *p) { _builtin_set_gbr(p); }
void *sa1g_get_gbr(void) { return _builtin_get_gbr(); }

/* R7 runtime data: XMTRX is the interpreter's XF bank (as rt.h's harness profile) */
float *sa1_rt_xmtrx = SH4.xf.f;
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pclower", required=True, help="pclower output directory (functions.json, ga32/)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--exclude", action="append", default=[])
    ap.add_argument("--rt", action="store_true", help="the lowered set includes libsa1/src/rt (no pc_runtime pieces)")
    a = ap.parse_args()
    pdir = os.path.abspath(a.pclower)
    out = os.path.abspath(a.out)
    fj = json.load(open(os.path.join(pdir, "functions.json")))
    syms = gn.load_symbols()
    src_out = os.path.join(out, "ga_src")
    os.makedirs(src_out, exist_ok=True)
    for old in os.listdir(src_out):
        if old.endswith(".c"):
            os.unlink(os.path.join(src_out, old))
    gn.gen_overlays(out)
    gn.gen_functions(out)
    excl = {os.path.basename(x) for x in a.exclude}
    units = {b: u for b, u in fj["units"].items() if b not in excl}
    manifest = {"files": {}, "excluded": {b: "--exclude" for b in fj["units"] if b in excl}}
    host_pcd = set(fj.get("host_provided_pcdata", []))
    provided_pcd = HARNESS_PCDATA if not a.rt else set()
    # exclusion: the TU needs runtime pieces the harness does not provide (as gen_native does for
    # unresolved names); iterate, since an excluded TU's functions become thunks
    while True:
        defined = {}
        for b, u in units.items():
            for d in u["defines"]:
                defined[d["name"]] = b
        bad = {}
        for b, u in units.items():
            for name in u["rt_calls"]:
                if name not in HARNESS_RT_FUNCS and name not in defined:
                    bad[b] = "runtime function %s is not provided by the harness" % name
            for name in u["rt_data"]:
                if name not in HARNESS_RT_DATA:
                    bad[b] = "runtime data %s is not provided by the harness" % name
            for name in u["pcdata_imports"]:
                if name in host_pcd and name not in provided_pcd:
                    bad[b] = "pcdata %s is not provided by the harness" % name
            for name, e in u["externs"].items():
                if name in defined:
                    continue
                if int(e["addr"], 16) == 0:
                    bad[b] = "external function %s has no DC address" % name
        if not bad:
            break
        for b, why in bad.items():
            manifest["excluded"][b] = why
            units.pop(b)
    defined = {}
    for b, u in units.items():
        for d in u["defines"]:
            defined[d["name"]] = (b, d)
    # externals: per-unit ABI signature; variant 0 (most common) keeps the name
    ext = collections.defaultdict(dict)
    eaddr = {}
    for b, u in units.items():
        for name, e in u["externs"].items():
            if name in defined:
                continue
            sig = R7_SIGS.get(name) or e["sig"]
            ext[name][b] = sig
            eaddr[name] = int(e["addr"], 16)
    renames = collections.defaultdict(dict)
    thunks = {}
    conflicts = {}
    for name, per in sorted(ext.items()):
        cnt = collections.Counter(per.values())
        order = sorted(cnt, key=lambda s: (-cnt[s], s))
        thunks[name] = (eaddr[name], order[0])
        if len(order) > 1:
            conflicts[name] = {s: sorted(b for b, x in per.items() if x == s) for s in order}
            if name in pcl.GUEST_H_FUNCS:
                continue        # declared once in sa1/guest.h: one thunk, the guest.h prototype
            for i, s in enumerate(order[1:], 1):
                vn = "%s__s%d" % (name, i)
                thunks[vn] = (eaddr[name], s)
                for b, x in per.items():
                    if x == s:
                        renames[b][name] = vn
    # code map of the included set: lowered definitions, everything else external (thunks)
    entries = []
    for name, (b, d) in sorted(defined.items()):
        ad = int(d["addr"], 16)
        if ad:
            entries.append((ad, name, d["sig"], "def"))
    for name in sorted(ext):
        if eaddr[name]:
            entries.append((eaddr[name], name, thunks[name][1], "extern"))
    best = {}
    for e in entries:
        k = e[0] & 0x1FFFFFFF
        if k not in best or (e[3] == "def" and best[k][3] != "def"):
            best[k] = e
    entries = sorted(best.values(), key=lambda x: x[0] & 0x1FFFFFFF)
    with open(os.path.join(out, "sa1g_fntab.c"), "w", newline="\n") as f:
        f.write(pcl.gen_fntab(entries))

    class U(object):
        pass
    pus = []
    for b, u in sorted(units.items()):
        if u["pcdata"]:
            x = U()
            x.pcd, x.uname, x.lowered = True, pcl.sanitize(b), True
            pus.append(x)
    with open(os.path.join(out, "sa1g_pcdata.c"), "w", newline="\n") as f:
        f.write(pcl.gen_pcdata(pus))
    # lowered sources
    for b in sorted(units):
        text = open(os.path.join(pdir, "ga32", "lowered", b), encoding="latin-1").read()
        ren = renames.get(b)
        if ren:
            first, _, rest = text.partition('#include "sa1/guest.h"\n')
            text = first + '#include "sa1/guest.h"\n' + "".join(
                "#define %s %s /* conflicting prototypes across TUs (gen_ga) */\n" % (k, v)
                for k, v in sorted(ren.items())) + rest
        with open(os.path.join(src_out, b), "w", encoding="latin-1", newline="\n") as f:
            f.write(text)
        manifest["files"][b] = {"defines": len(units[b]["defines"]), "renames": ren or {}}
    # thunks
    with open(os.path.join(out, "native_thunks.c"), "w", newline="\n") as f:
        f.write(HDR + "void sh4_unsupported_call(const char *name, uint32_t guest);\n\n")
        for name in sorted(thunks):
            ad, sig = thunks[name]
            f.write(emit_thunk(name, ad, sig) + "\n\n")
    with open(os.path.join(out, "native_abs.c"), "w", newline="\n") as f:
        f.write("/* Generated by harness/tools/gen_ga.py: lowered code has no absolute symbols */\n"
                "typedef int native_abs_empty;\n")
    # registry
    natives = sorted((d["name"], b, d) for name, (b, d) in defined.items())
    with open(os.path.join(out, "native_registry.c"), "w", newline="\n") as f:
        f.write(HDR)
        f.write("static inline __attribute__((unused)) float sh4_u2f(uint32_t u) "
                "{ union { uint32_t u; float f; } x; x.u = u; return x.f; }\n")
        f.write("static inline __attribute__((unused)) sa1_gfn sa1g_gfn_of(uint32_t v) "
                "{ sa1_gfn g; g.v = v; return g; }\n\n")
        adapters = set()
        for name, b, d in natives:
            if int(d["addr"], 16) and adapter_ok(d["sig"]) and name not in gn.NO_ROUTE:
                f.write(emit_adapter(name, d["sig"]) + "\n\n")
                adapters.add(name)
            else:
                f.write("extern void %s(void);\n" % name)
        for name in sorted(thunks):
            f.write("extern void %s(void);\n" % name)
        f.write("\nconst sh4_native_fn sh4_native_fns[] = {\n")
        for name, b, d in natives:
            f.write('    { 0x%08Xu, (void *)%s, %s, "%s", "%s", "%s" },\n' % (
                int(d["addr"], 16), name, ("adapt_" + name) if name in adapters else "0", name,
                harness_sig(d["sig"]), b))
        if not natives:
            f.write('    { 0, 0, 0, "", "", "" },\n')
        f.write("};\nconst int sh4_native_fn_count = %d;\n\n" % len(natives))
        f.write("const sh4_thunk_info sh4_thunks[] = {\n")
        for name in sorted(thunks):
            ad, sig = thunks[name]
            f.write('    { 0x%08Xu, (void *)%s, "%s", "%s" },\n' % (ad, name, name, harness_sig(sig)))
        if not thunks:
            f.write('    { 0, 0, "", "" },\n')
        f.write("};\nconst int sh4_thunk_count = %d;\n\n" % len(thunks))
        addrs = sorted(set(syms.values()))
        f.write("const sh4_native_data sh4_native_datas[] = {\n")
        nd = 0
        for b in sorted(units):
            for name, ad in sorted(units[b]["globals"].items()):
                ad = int(ad, 16)
                k = bisect.bisect_right(addrs, ad)
                gap = (addrs[k] - ad) if k < len(addrs) else 256
                f.write('    { "%s", 0x%08Xu, %du, "%s" },\n' % (name, ad, min(gap, 1024), b))
                nd += 1
        if not nd:
            f.write('    { "", 0, 0, "" },\n')
        f.write("};\nconst int sh4_native_data_count = %d;\n" % nd)
        gn.emit_image_guard(f, [units[b].get("image") or gn.BASE_IMAGE for name, b, d in natives])
    manifest["images"] = {img: {k: v for k, v in gn.image_guard_info(img).items() if k != "ranges"}
                          for img in sorted({u.get("image") or gn.BASE_IMAGE for u in units.values()} -
                                            {gn.BASE_IMAGE})}
    # glue
    glue = [GLUE]
    used_pcd = sorted(set().union(*[set(u["pcdata_imports"]) for u in units.values()]) & host_pcd) if units else []
    for name in used_pcd:
        glue.append("extern unsigned char %s[]; /* harness/src/pc_runtime.c */" % name)
        glue.append("uint32_t sa1g_pcdv_%s;" % name)
    glue.append("")
    glue.append("/* R4: pcdata in each unit's static storage, host-provided PC-only data exported, before main() */")
    glue.append("__attribute__((constructor)) static void sa1g_ga_init(void)")
    glue.append("{")
    for name in used_pcd:
        glue.append("    sa1g_pcdv_%s = (uint32_t)(uintptr_t)%s;" % (name, name))
    glue.append("    sa1g_pcd_init();")
    glue.append("}")
    with open(os.path.join(out, "ga_glue.c"), "w", newline="\n") as f:
        f.write("\n".join(glue) + "\n")
    manifest["native_functions"] = len(natives)
    manifest["adapters"] = len(adapters)
    manifest["thunks"] = len(thunks)
    manifest["signature_conflicts"] = conflicts
    manifest["code_map_entries"] = len(entries)
    with open(os.path.join(out, "ga_manifest.json"), "w", newline="\n") as f:
        json.dump(manifest, f, indent=1)
    print("gen_ga: %d/%d lowered TUs, %d functions (%d adapters), %d thunks (%d ABI variants), %d code-map entries" % (
        len(units), len(fj["units"]), len(natives), len(adapters), len(thunks),
        sum(1 for t in thunks if "__s" in t), len(entries)))
    for b, why in sorted(manifest["excluded"].items()):
        print("  %s: excluded: %s" % (b, why))
    return 0


