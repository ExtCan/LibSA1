#!/usr/bin/env python3
"""Generate build.ninja for the Sonic Adventure (DC) decompilation.

    py -3.12 configure.py [--split]     # then:  py -3.12 -m ninja

Every image listed in IMAGES has a split config in config/<image>.yaml;
--split (re)generates asm/<image>/ and build/<IMAGE>.manifest.json.

C sources live in src/<image>/. Any function defined there whose name is in
the image's symbol table replaces the matching assembly: the chunk that holds
it is rebuilt from the compiler output via tools/splice.py, which also
verifies the function matches the original exactly.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable.replace("\\", "/")


def image_configs():
    """config/1st_read.yaml first (overlays link against it), then overlays."""
    import glob
    cfgs = [os.path.join(ROOT, "config", "1st_read.yaml")]
    cfgs += sorted(glob.glob(os.path.join(ROOT, "config", "overlays", "*.yaml")))
    return cfgs


def split_one(cfg_path):
    r = subprocess.run([sys.executable, "tools/split/split.py", cfg_path], cwd=ROOT,
                       capture_output=True, text=True)
    return cfg_path, r.returncode, r.stdout[-400:] + r.stderr[-2000:]

ASFLAGS = "-cpu=sh4 -endian=little"

FUNC_DEF = re.compile(r"^(?!typedef|struct|union|enum|extern|#|//|/\*)[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(([^;{}]*)\)\s*(\{.*)?$")


def winp(p):
    return p.replace("/", "\\")


FUNC_START = re.compile(r"^(?!typedef|struct|union|enum|extern|static\s+const|#|//|/\*)[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(")


def c_functions(path):
    """Names of the functions defined in a C file (definitions start at column
    0; the parameter list may span several lines)."""
    names = []
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    for i, l in enumerate(lines):
        m = FUNC_DEF.match(l)
        if m:
            nxt = lines[i + 1].strip() if i + 1 < len(lines) else ""
            if m.group(3) or nxt.startswith("{"):
                names.append(m.group(1))
            continue
        m = FUNC_START.match(l)
        if not m or ";" in l:
            continue
        # parameter list continued on the following lines
        depth = l.count("(") - l.count(")")
        j = i
        while depth > 0 and j + 1 < len(lines) and j - i < 12:
            j += 1
            if ";" in lines[j] or "{" in lines[j].split(")")[0]:
                break
            depth += lines[j].count("(") - lines[j].count(")")
        if depth != 0 or j == i:
            continue
        rest = lines[j][lines[j].rfind(")") + 1:].strip()
        nxt = lines[j + 1].strip() if j + 1 < len(lines) else ""
        if rest.startswith("{") or (not rest and nxt.startswith("{")):
            names.append(m.group(1))
    return names


def load_symtab(name):
    tab = {}
    p = os.path.join(ROOT, "build", f"{name}.symbols.txt")
    for line in open(p):
        n, v = line.split("=")
        tab[n.strip()] = int(v.strip().rstrip(";"), 16)
    return tab


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", action="store_true", help="(re)run the splitter first")
    ap.add_argument("--only", help="comma-separated config names to include (e.g. 1st_read,stg01)")
    args = ap.parse_args()

    cfgs = image_configs()
    if args.only:
        cfgs = [c for c in cfgs if os.path.splitext(os.path.basename(c))[0] in args.only.split(",")]
    if args.split:
        from concurrent.futures import ProcessPoolExecutor
        first, rest = cfgs[:1], cfgs[1:]
        for c in first:
            subprocess.check_call([PY, "tools/split/split.py", c], cwd=ROOT)
        with ProcessPoolExecutor(max_workers=os.cpu_count()) as ex:
            for path, rc, out in ex.map(split_one, rest):
                if rc:
                    sys.exit(f"split failed for {path}:\n{out}")
        print(f"split {len(cfgs)} images")

    cc = json.load(open(os.path.join(ROOT, "tools", "compiler.json")))
    out = []
    w = out.append
    w("# generated by configure.py -- do not edit")
    w(f"python = {PY}")
    w(f"hitachi = $python tools/hitachi.py --ver {cc['version']}")
    w(f"cflags = {cc['cflags']} -include={','.join(cc['include'])}")
    w("")
    w("rule as")
    w(f"  command = $hitachi asmsh $in {ASFLAGS} -object=$out")
    w("  description = AS $in")
    w("rule cc")
    w("  command = $hitachi shc $in $cflags -code=asmcode -objectfile=$out")
    w("  description = CC $in")
    w("rule splice")
    w("  command = $python tools/splice.py $image $chunk $out $compiled")
    w("  description = SPLICE $out")
    w("rule gensym")
    w("  command = $python tools/gensym.py $in $out")
    w("  description = GENSYM $out")
    w("rule link")
    w("  command = $hitachi lnk -sub=$sub")
    w("  description = LINK $out")
    w("rule bin")
    w("  command = $python tools/rof2bin.py $in $out $base $end")
    w("  description = BIN $out")
    w("rule check")
    w("  command = $python tools/check.py $in $expected $out")
    w("  description = CHECK $in")
    w("")
    w("rule prs")
    w("  command = $python tools/prs.py c $in $out")
    w("  description = PRS $out")
    w("")
    all_checks = []
    total_c = 0
    for cfg_path in cfgs:
        import yaml
        cfg = yaml.safe_load(open(cfg_path))
        man_path = os.path.join(ROOT, "build", f"{cfg['name']}.manifest.json")
        if not os.path.exists(man_path):
            print(f"skipping {cfg['name']}: not split yet (run configure.py --split)")
            continue
        man = json.load(open(man_path))
        name = man["name"]
        img = (man.get("asm_dir") or f"asm/{name.lower()}").replace("asm/", "", 1)
        symtab = load_symtab(name)
        func_chunk = {}
        for ch in man["chunks"]:
            for a, n in ch["functions"]:
                func_chunk[a] = ch["src"]
        # C sources -> compiled .src, and which chunks they touch
        chunk_c = {}
        # SHC cannot emit dependency files: every C file depends on every header
        headers = sorted(os.path.relpath(os.path.join(dp, f), ROOT).replace("\\", "/")
                         for dp, dn, fn in os.walk(os.path.join(ROOT, "include")) for f in fn if f.endswith(".h"))
        src_dir = os.path.join(ROOT, "src", img)
        for dp, dn, fn in os.walk(src_dir):
            for f in sorted(fn):
                if not f.endswith(".c"):
                    continue
                cpath = os.path.relpath(os.path.join(dp, f), ROOT).replace("\\", "/")
                csrc = "build/" + cpath[:-2] + ".src"
                w(f"build {csrc}: cc {cpath} | {' '.join(headers)}")
                for fname in c_functions(os.path.join(ROOT, cpath)):
                    a = symtab.get(fname)
                    if a in func_chunk:
                        chunk_c.setdefault(func_chunk[a], set()).add(csrc)
        objs = []
        for ch in man["chunks"]:
            src = ch["src"]
            obj = "build/" + src.rsplit(".", 1)[0] + ".obj"
            objs.append(obj)
            if src in chunk_c:
                spliced = "build/spliced/" + src
                comp = sorted(chunk_c[src])
                w(f"build {spliced}: splice {src} {' '.join(comp)} | tools/splice.py tools/shcdiff.py")
                w(f"  image = {name}")
                w(f"  chunk = {src}")
                w(f"  compiled = {' '.join(comp)}")
                w(f"build {obj}: as {spliced}")
            else:
                w(f"build {obj}: as {src}")
        for other in man.get("link_with", []):
            ext_src = f"build/{name}_{other}_syms.src"
            ext_obj = f"build/{name}_{other}_syms.obj"
            w(f"build {ext_src}: gensym build/{other}.symbols.txt build/{name}.imports.txt")
            w(f"build {ext_obj}: as {ext_src}")
            objs.append(ext_obj)
        sub = f"build/{name}.sub"
        absf = f"build/{name}.abs"
        with open(os.path.join(ROOT, sub), "w", newline="\n") as f:
            for o in objs:
                f.write(f"INPUT {winp(o)}\n")
            f.write(f"OUTPUT {winp(absf)}\n")
            f.write("FORM A\n")
            f.write(f"START {','.join(man['sections'])}({man['base']:08X})\n")
            f.write(f"PRINT {winp('build/' + name + '.map')}\n")
            f.write("EXIT\n")
        w(f"build {absf}: link {' '.join(objs)} | {sub}")
        w(f"  sub = {sub}")
        binf = f"build/{name}.BIN"
        w(f"build {binf}: bin {absf}")
        w(f"  base = {man['base']:08X}")
        w(f"  end = {man['end']:08X}")
        ok = f"build/{name}.ok"
        w(f"build {ok}: check {binf}")
        w(f"  expected = {man['sha1']}")
        all_checks.append(ok)
        if man.get("prs") and man.get("prs_sha1"):
            prsf = f"build/SONICADV/{os.path.basename(man['prs'])}"
            w(f"build {prsf}: prs {binf}")
            w(f"build {prsf}.ok: check {prsf}")
            w(f"  expected = {man['prs_sha1']}")
            all_checks.append(prsf + ".ok")
        total_c += sum(1 for v in chunk_c.values())
        w("")
    print(f"{len(all_checks)} checked outputs, {total_c} chunks with C code")
    w(f"build all: phony {' '.join(all_checks)}")
    w("default all")
    with open(os.path.join(ROOT, "build.ninja"), "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote build.ninja")


if __name__ == "__main__":
    main()
