<#
.SYNOPSIS
  Run Ghidra's AnalyzeHeadless with the bundled JDK, bypassing analyzeHeadless.bat.

.DESCRIPTION
  analyzeHeadless.bat / launch.bat break on any argument containing ")" (they expand
  arguments unquoted inside parenthesized blocks) and this tree may live under a
  folder such as "C:\SA1 (decomp)". This wrapper replicates launch.bat (LaunchSupport -vmargs,
  -Xmx, Utility.jar classpath, ghidra.Ghidra main) and writes the exact command line to a
  .cmd file (every argument double-quoted) which is then executed with output to -Log.

.EXAMPLE
  # print a listing range from an existing project (read-only)
  ghidra_headless.ps1 -Log dump.out -HeadlessArgs @(
      "C:\SA1 (decomp)\sadc\build\ghidra\projects", "1ST_READ",
      "-process", "1ST_READ.BIN", "-noanalysis", "-readOnly",
      "-scriptPath", "C:\SA1 (decomp)\sadc\tools\ghidra\scripts",
      "-postScript", "SadcDump.java", "8C010000-8C010100")
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string[]]$HeadlessArgs,
    [string]$Log,
    [string]$CmdFile,
    [string]$MaxMem = "16G",
    [switch]$DryRun
)
$ErrorActionPreference = "Stop"
$Sadc = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$Ghidra = Join-Path $Sadc "tools\ghidra_12.1.4_PUBLIC"
$Jdk = Join-Path $Sadc "tools\jdk-21.0.12.1+1"
$java = Join-Path $Jdk "bin\java.exe"
$launchSupport = Join-Path $Ghidra "support\LaunchSupport.jar"

$vmargs = @(& $java -cp $launchSupport LaunchSupport $Ghidra -vmargs | Where-Object { $_ -and $_.Trim() })
if ($LASTEXITCODE -ne 0 -or $vmargs.Count -eq 0) { throw "LaunchSupport -vmargs failed" }
$vmargs += @("-Duser.home=$env:USERPROFILE", "-Xmx$MaxMem", "-XX:ParallelGCThreads=4", "-XX:CICompilerCount=2")
$jargs = $vmargs + @("-cp", (Join-Path $Ghidra "Ghidra\Framework\Utility\lib\Utility.jar"),
                     "ghidra.Ghidra", "ghidra.app.util.headless.AnalyzeHeadless") + $HeadlessArgs
foreach ($x in $jargs) {
    if ($x.Contains('"') -or $x.Contains('%')) { throw "argument contains a quote or percent sign: $x" }
    if ($x.EndsWith('\')) { throw "argument ends with a backslash (breaks quoting): $x" }
}
$quoted = ($jargs | ForEach-Object { '"' + $_ + '"' }) -join " "
if (-not $CmdFile) { $CmdFile = Join-Path ([IO.Path]::GetTempPath()) ("ghidra_headless_{0}.cmd" -f $PID) }
$redir = if ($Log) { " > `"$Log`" 2>&1" } else { "" }
$cmdText = @(
    "@echo off",
    "rem generated by sadc/tools/ghidra/ghidra_headless.ps1 (run this file to repeat)",
    "set `"JAVA_HOME=$Jdk`"",
    "`"$java`" $quoted$redir",
    "exit /b %ERRORLEVEL%"
) -join "`r`n"
[IO.File]::WriteAllText($CmdFile, $cmdText + "`r`n", [Text.Encoding]::ASCII)
if ($DryRun) { Get-Content $CmdFile; exit 0 }
& $CmdFile
exit $LASTEXITCODE
